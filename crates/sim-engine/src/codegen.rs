//! Standalone Embedded Code Generator (Simulink Coder equivalent).
//! Transpiles continuous/discrete `SimModel` diagrams and `StateChart` state machines
//! into zero-allocation, deterministic `#![no_std]` Rust and ANSI C.

use crate::{BlockKind, SimModel, StateChart, TransitionGuard};

/// Generates deterministic, allocation-free ANSI C code from a `SimModel`.
#[must_use]
pub fn generate_c_code(model: &SimModel) -> String {
    let mut code = String::from("/* Auto-generated by MatCraft Embedded Coder (C) */\n");
    code.push_str("#include <math.h>\n#include <stdint.h>\n\n");

    // State structure
    code.push_str("typedef struct {\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Integrator { .. } => {
                code.push_str(&format!("    double state_integrator_{id};\n"));
            }
            BlockKind::TransferFcn { .. } => {
                code.push_str(&format!("    double state_tf_{id}[2];\n"));
            }
            BlockKind::PidController { .. } => {
                code.push_str(&format!("    double state_pid_{id}[2];\n"));
            }
            _ => {}
        }
    }
    code.push_str("} MatCraftModelStates;\n\n");

    // Init function
    code.push_str("void matcraft_model_init(MatCraftModelStates* s) {\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Integrator { initial_state } => {
                code.push_str(&format!("    s->state_integrator_{id} = {initial_state:.8e};\n"));
            }
            BlockKind::TransferFcn { .. } => {
                code.push_str(&format!("    s->state_tf_{id}[0] = 0.0;\n    s->state_tf_{id}[1] = 0.0;\n"));
            }
            BlockKind::PidController { .. } => {
                code.push_str(&format!("    s->state_pid_{id}[0] = 0.0;\n    s->state_pid_{id}[1] = 0.0;\n"));
            }
            _ => {}
        }
    }
    code.push_str("}\n\n");

    // Step function
    code.push_str("void matcraft_model_step(MatCraftModelStates* s, double t, double dt) {\n");
    code.push_str("    /* 1. Evaluate outputs and feedforward signals */\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Constant { value } => {
                code.push_str(&format!("    double out_{id} = {value:.8e};\n"));
            }
            BlockKind::Step { step_time, initial_val, final_val } => {
                code.push_str(&format!("    double out_{id} = (t >= {step_time:.8e}) ? {final_val:.8e} : {initial_val:.8e};\n"));
            }
            BlockKind::SineWave { amplitude, freq_rad_s, phase_rad } => {
                code.push_str(&format!("    double out_{id} = {amplitude:.8e} * sin({freq_rad_s:.8e} * t + {phase_rad:.8e});\n"));
            }
            BlockKind::Integrator { .. } => {
                code.push_str(&format!("    double out_{id} = s->state_integrator_{id};\n"));
            }
            BlockKind::TransferFcn { b0, b1, .. } => {
                code.push_str(&format!("    double out_{id} = {b0:.8e} * s->state_tf_{id}[0] + {b1:.8e} * s->state_tf_{id}[1];\n"));
            }
            BlockKind::Gain { gain } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    double out_{id} = {gain:.8e} * ({u_expr});\n"));
            }
            BlockKind::Sum { ref signs } => {
                let mut sum_str = String::from("0.0");
                for (p, &sgn) in signs.iter().enumerate() {
                    let u_expr = get_c_input_expr(model, id, p);
                    if sgn >= 0.0 {
                        sum_str.push_str(&format!(" + {u_expr}"));
                    } else {
                        sum_str.push_str(&format!(" - {u_expr}"));
                    }
                }
                code.push_str(&format!("    double out_{id} = {sum_str};\n"));
            }
            BlockKind::Saturation { lower, upper } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    double u_{id} = {u_expr};\n"));
                code.push_str(&format!("    double out_{id} = (u_{id} > {upper:.8e}) ? {upper:.8e} : ((u_{id} < {lower:.8e}) ? {lower:.8e} : u_{id});\n"));
            }
            BlockKind::PidController { kp, .. } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    double out_{id} = {kp:.8e} * ({u_expr}) + s->state_pid_{id}[0];\n"));
            }
            _ => {
                code.push_str(&format!("    double out_{id} = 0.0;\n"));
            }
        }
    }

    code.push_str("\n    /* 2. Euler/RK integration updates for states */\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Integrator { .. } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    s->state_integrator_{id} += dt * ({u_expr});\n"));
            }
            BlockKind::TransferFcn { a1, a0, .. } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    double dx0_{id} = s->state_tf_{id}[1];\n"));
                code.push_str(&format!("    double dx1_{id} = ({u_expr}) - {a1:.8e} * s->state_tf_{id}[1] - {a0:.8e} * s->state_tf_{id}[0];\n"));
                code.push_str(&format!("    s->state_tf_{id}[0] += dt * dx0_{id};\n"));
                code.push_str(&format!("    s->state_tf_{id}[1] += dt * dx1_{id};\n"));
            }
            BlockKind::PidController { ki, .. } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("    s->state_pid_{id}[0] += dt * {ki:.8e} * ({u_expr});\n"));
            }
            _ => {}
        }
    }

    code.push_str("}\n");
    code
}

fn get_c_input_expr(model: &SimModel, dst_block: usize, dst_port: usize) -> String {
    for w in &model.wires {
        if w.dst_block == dst_block && w.dst_port == dst_port {
            return format!("out_{}", w.src_block);
        }
    }
    "0.0".to_string()
}

/// Generates `#![no_std]` Rust code from a `SimModel`.
#[must_use]
pub fn generate_no_std_rust_code(model: &SimModel) -> String {
    let mut code = String::from("//! Auto-generated by MatCraft Embedded Coder (Rust no_std)\n#![no_std]\n\n");

    code.push_str("#[derive(Clone, Copy, Debug, Default)]\npub struct MatCraftModelStates {\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Integrator { .. } => {
                code.push_str(&format!("    pub state_integrator_{id}: f64,\n"));
            }
            BlockKind::TransferFcn { .. } => {
                code.push_str(&format!("    pub state_tf_{id}: [f64; 2],\n"));
            }
            BlockKind::PidController { .. } => {
                code.push_str(&format!("    pub state_pid_{id}: [f64; 2],\n"));
            }
            _ => {}
        }
    }
    code.push_str("}\n\nimpl MatCraftModelStates {\n");

    // new()
    code.push_str("    pub const fn new() -> Self {\n        Self {\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Integrator { initial_state } => {
                code.push_str(&format!("            state_integrator_{id}: {initial_state:.8e},\n"));
            }
            BlockKind::TransferFcn { .. } => {
                code.push_str(&format!("            state_tf_{id}: [0.0, 0.0],\n"));
            }
            BlockKind::PidController { .. } => {
                code.push_str(&format!("            state_pid_{id}: [0.0, 0.0],\n"));
            }
            _ => {}
        }
    }
    code.push_str("        }\n    }\n\n");

    // step()
    code.push_str("    pub fn step(&mut self, t: f64, dt: f64) {\n");
    for (&id, blk) in &model.blocks {
        match blk.kind {
            BlockKind::Constant { value } => {
                code.push_str(&format!("        let out_{id} = {value:.8e};\n"));
            }
            BlockKind::Step { step_time, initial_val, final_val } => {
                code.push_str(&format!("        let out_{id} = if t >= {step_time:.8e} {{ {final_val:.8e} }} else {{ {initial_val:.8e} }};\n"));
            }
            BlockKind::Integrator { .. } => {
                code.push_str(&format!("        let out_{id} = self.state_integrator_{id};\n"));
            }
            BlockKind::Gain { gain } => {
                let u_expr = get_c_input_expr(model, id, 0);
                code.push_str(&format!("        let out_{id} = {gain:.8e} * ({u_expr});\n"));
            }
            BlockKind::Sum { ref signs } => {
                let mut sum_str = String::from("0.0");
                for (p, &sgn) in signs.iter().enumerate() {
                    let u_expr = get_c_input_expr(model, id, p);
                    if sgn >= 0.0 {
                        sum_str.push_str(&format!(" + {u_expr}"));
                    } else {
                        sum_str.push_str(&format!(" - {u_expr}"));
                    }
                }
                code.push_str(&format!("        let out_{id} = {sum_str};\n"));
            }
            _ => {
                code.push_str(&format!("        let out_{id} = 0.0;\n"));
            }
        }
    }

    code.push_str("\n        // State updates\n");
    for (&id, blk) in &model.blocks {
        if matches!(blk.kind, BlockKind::Integrator { .. }) {
            let u_expr = get_c_input_expr(model, id, 0);
            code.push_str(&format!("        self.state_integrator_{id} += dt * ({u_expr});\n"));
        }
    }

    code.push_str("    }\n}\n");
    code
}

fn sanitize_c_ident(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        format!("s_{out}")
    } else {
        out
    }
}

/// Generates a static-memory C finite state machine stepper for a `StateChart`.
#[must_use]
pub fn generate_stateflow_c_code(chart: &StateChart) -> String {
    let mut code = String::from("/* Auto-generated Stateflow C Stepper */\n#include <stdint.h>\n\n");

    let state_names: Vec<String> = chart.states.keys().map(|k| sanitize_c_ident(k)).collect();
    code.push_str("typedef enum {\n");
    for name in &state_names {
        code.push_str(&format!("    STATE_{name},\n"));
    }
    code.push_str("} StateflowState;\n\n");

    code.push_str("typedef struct {\n");
    code.push_str("    StateflowState current_state;\n");
    code.push_str("    uint64_t ticks_in_state;\n");
    code.push_str("} StateflowFsm;\n\n");

    let init_state = sanitize_c_ident(&chart.active_state);
    code.push_str("void stateflow_init(StateflowFsm* fsm) {\n");
    code.push_str(&format!("    fsm->current_state = STATE_{init_state};\n"));
    code.push_str("    fsm->ticks_in_state = 0;\n}\n\n");

    code.push_str("void stateflow_step(StateflowFsm* fsm, double signal_val) {\n");
    code.push_str("    fsm->ticks_in_state++;\n");
    code.push_str("    switch (fsm->current_state) {\n");

    for from_state in chart.states.keys() {
        let from_clean = sanitize_c_ident(from_state);
        code.push_str(&format!("    case STATE_{from_clean}:\n"));
        for tr in &chart.transitions {
            if tr.from_state == *from_state {
                let to_clean = sanitize_c_ident(&tr.to_state);
                match &tr.guard {
                    TransitionGuard::AfterTicks(t) => {
                        code.push_str(&format!("        if (fsm->ticks_in_state >= {t}) {{\n"));
                        code.push_str(&format!("            fsm->current_state = STATE_{to_clean};\n"));
                        code.push_str("            fsm->ticks_in_state = 0;\n            break;\n        }\n");
                    }
                    TransitionGuard::InputGreaterThan { threshold, .. } => {
                        code.push_str(&format!("        if (signal_val > {threshold:.8e}) {{\n"));
                        code.push_str(&format!("            fsm->current_state = STATE_{to_clean};\n"));
                        code.push_str("            fsm->ticks_in_state = 0;\n            break;\n        }\n");
                    }
                    TransitionGuard::InputLessThan { threshold, .. } => {
                        code.push_str(&format!("        if (signal_val < {threshold:.8e}) {{\n"));
                        code.push_str(&format!("            fsm->current_state = STATE_{to_clean};\n"));
                        code.push_str("            fsm->ticks_in_state = 0;\n            break;\n        }\n");
                    }
                    _ => {}
                }
            }
        }
        code.push_str("        break;\n");
    }

    code.push_str("    }\n}\n");
    code
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{SimBlock, StateNode, StateTransition};
    use num_core::SiUnit;

    #[test]
    fn test_generate_c_and_rust_code_for_feedback_loop() {
        let mut model = SimModel::new();
        let step = SimBlock {
            id: 1,
            name: "Step".into(),
            kind: BlockKind::Step { step_time: 1.0, initial_val: 0.0, final_val: 1.0 },
            out_unit: SiUnit::DIMENSIONLESS,
        };
        let sum = SimBlock {
            id: 2,
            name: "Sum".into(),
            kind: BlockKind::Sum { signs: vec![1.0, -1.0] },
            out_unit: SiUnit::DIMENSIONLESS,
        };
        let integ = SimBlock {
            id: 3,
            name: "Integrator".into(),
            kind: BlockKind::Integrator { initial_state: 0.0 },
            out_unit: SiUnit::DIMENSIONLESS,
        };

        model.add_block(step);
        model.add_block(sum);
        model.add_block(integ);

        assert!(model.connect(1, 2, 0).is_ok());
        assert!(model.connect(3, 2, 1).is_ok()); // feedback
        assert!(model.connect(2, 3, 0).is_ok());

        let c_code = generate_c_code(&model);
        assert!(c_code.contains("matcraft_model_init"));
        assert!(c_code.contains("matcraft_model_step"));
        assert!(c_code.contains("state_integrator_3"));

        let rust_code = generate_no_std_rust_code(&model);
        assert!(rust_code.contains("#![no_std]"));
        assert!(rust_code.contains("pub fn step"));
    }

    #[test]
    fn test_generate_stateflow_c_code() {
        let mut chart = StateChart::new("Off");
        chart.add_state(StateNode {
            name: "Off".into(),
            entry_outputs: Default::default(),
            during_outputs: Default::default(),
        });
        chart.add_state(StateNode {
            name: "On".into(),
            entry_outputs: Default::default(),
            during_outputs: Default::default(),
        });
        chart.transitions.push(StateTransition {
            from_state: "Off".into(),
            to_state: "On".into(),
            guard: TransitionGuard::AfterTicks(10),
            priority: 1,
        });

        let c_code = generate_stateflow_c_code(&chart);
        assert!(c_code.contains("STATE_Off"));
        assert!(c_code.contains("STATE_On"));
        assert!(c_code.contains("ticks_in_state >= 10"));
    }
}

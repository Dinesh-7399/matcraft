use crate::AiLocalError;
use lang_m::{BinOp, Expr, Parser, tokenize};

/// Offline `.m`-Expression-to-WGSL GPU Compute Shader Compiler (`wgsl_codegen.rs`).
/// Lowers vectorized `.m` array expressions (like `sin(A) .* B + 2.5`) directly into a
/// standalone 256-thread workgroup WebGPU/WGSL compute kernel!
pub fn compile_m_expr_to_wgsl_shader(
    kernel_name: &str,
    m_expr_source: &str,
) -> Result<String, AiLocalError> {
    let tokens = tokenize(m_expr_source).map_err(|e| AiLocalError::CodegenError(e.to_string()))?;
    let mut parser = Parser::new(tokens);
    let expr = parser
        .parse_expr()
        .map_err(|e| AiLocalError::CodegenError(e.to_string()))?;

    let body_wgsl = lower_expr_to_wgsl(&expr);
    let shader = format!(
        "// Auto-generated by MatCraft Offline .m-to-WGSL GPU Kernel Compiler\n\
         @group(0) @binding(0) var<storage, read> in_a: array<f32>;\n\
         @group(0) @binding(1) var<storage, read> in_b: array<f32>;\n\
         @group(0) @binding(2) var<storage, read_write> out_c: array<f32>;\n\
         \n\
         @compute @workgroup_size(256, 1, 1)\n\
         fn {kernel_name}(@builtin(global_invocation_id) gid: vec3<u32>) {{\n\
             let i = gid.x;\n\
             if (i >= arrayLength(&out_c)) {{\n\
                 return;\n\
             }}\n\
             let A: f32 = in_a[i];\n\
             let B: f32 = in_b[i];\n\
             out_c[i] = {body_wgsl};\n\
         }}\n"
    );
    Ok(shader)
}

fn lower_expr_to_wgsl(expr: &Expr) -> String {
    match expr {
        Expr::Literal(v, _) => format!("{v:.6}"),
        Expr::Var(name) => name.clone(),
        Expr::UnaryNeg(inner) => format!("(-{})", lower_expr_to_wgsl(inner)),
        Expr::Binary { op, lhs, rhs } => {
            let l = lower_expr_to_wgsl(lhs);
            let r = lower_expr_to_wgsl(rhs);
            match op {
                BinOp::Add => format!("({l} + {r})"),
                BinOp::Sub => format!("({l} - {r})"),
                BinOp::MatMul | BinOp::ElemMul => format!("({l} * {r})"),
                BinOp::RightDiv | BinOp::ElemDiv => format!("({l} / {r})"),
                BinOp::Pow | BinOp::ElemPow => format!("pow({l}, {r})"),
                _ => format!("({l} + {r})"),
            }
        }
        Expr::CallOrIndex { name, args } => {
            let a0 = args
                .first()
                .map_or_else(|| "0.0".to_string(), lower_expr_to_wgsl);
            match name.as_str() {
                "sin" | "cos" | "tan" | "exp" | "sqrt" | "abs" => format!("{name}({a0})"),
                _ => a0,
            }
        }
        _ => "0.0".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_m_to_wgsl_shader_compiler() -> Result<(), Box<dyn std::error::Error>> {
        let wgsl = compile_m_expr_to_wgsl_shader("fused_kernel", "sin(A) .* B + 2.5")?;
        assert!(wgsl.contains("@compute @workgroup_size(256, 1, 1)"));
        assert!(wgsl.contains("((sin(A) * B) + 2.500000)"));
        Ok(())
    }
}
